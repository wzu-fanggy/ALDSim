# core/config.py
from dataclasses import dataclass


@dataclass
class SimuConfig:
    """
    整个 ALD 仿真系统通用配置参数
    对应论文 5.1 “仿真参数设置界面（图 5-1）”
    """

    # ===============================
    # 基本结构参数
    # ===============================
    SIMUSIZE: int = 100          # 晶体二维规模（默认 100×100）
    cycle_num: int = 50          # ALD 循环次数

    # ===============================
    # TMA 气体参数
    # ===============================
    T_TMA: float = 450.0         # 温度（单位 K）
    P_TMA: float = 40.0          # 压力（Pa）
    t_TMA: float = 0.10          # 脉冲时间（s）

    # ===============================
    # H₂O 气体参数
    # ===============================
    T_H2O: float = 450.0         # 温度（K）
    P_H2O: float = 40.0          # 压力（Pa）
    t_H2O: float = 0.10          # 脉冲时间（s）

    # ===============================
    # 清洗阶段（N₂、Ar 气体）
    # ===============================
    t_clean: float = 0.08        # 洗涤气体脉冲持续时间（s）

    # ===============================
    # 反应动力学参数
    # ===============================
    # Ea: float = 1.20e-19         # 反应活化能（J） 例：1.2×10⁻¹⁹
    # kB: float = 1.380649e-23     # Boltzmann 常数
    # NA: float = 6.02214076e23    # 阿伏伽德罗常数
    Ea_TMA: float = 1.20e-19  # A2：TMA + OH → AlCH3（J）
    Ea_H2O: float = 0.80e-19  # B6：H2O + AlCH3 → OH（J）

    kB: float = 1.380649e-23
    NA: float = 6.02214076e23

    # ===============================
    # 单元面积 / 分子量
    # ===============================
    cell_area: float = 1.0e-18   # 2D 单元面积（m²）
    MW_TMA: float = 0.0          # TMA 分子量（kg/mol，文章未给出，可填）
    MW_H2O: float = 0.0          # H₂O 分子量

    # ===============================
    # 可选：数据库路径
    # ===============================
    db_path: str = "data/ald.db"

    # ===============================
    # 可选：GUI 相关参数
    # ===============================
    auto_save_interval: float = 0.5
    enable_3d_view: bool = True